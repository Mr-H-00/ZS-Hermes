// 在隔离 Vite 页面执行：playwright-cli -s=reader run-code --filename=frontend/test/browser/externalDocumentReader.js
async (page) => {
  await page.goto(`${page.url().split('/test/')[0]}/test/browser/fixtures/externalDocumentReader.html`)
  const next = page.getByRole('button', { name: '下一页' })
  const previous = page.getByRole('button', { name: '上一页' })
  await page.getByText('A-0', { exact: true }).waitFor()
  await next.click()
  await page.getByText('A-3', { exact: true }).waitFor()
  await next.click()
  await page.getByText('A-7', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('A-3', { exact: true }).waitFor()
  await page.evaluate(() => { window.failNext = true })
  await next.click()
  await page.getByRole('alert').getByText('测试失败').waitFor()
  await page.getByText('重新读取').click()
  await page.getByText('A-7', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('A-3', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('A-0', { exact: true }).waitFor()
  await page.evaluate(() => { window.fixture.fileId = 'B' })
  await page.getByText('B-0', { exact: true }).waitFor()
  await page.evaluate(() => { window.blockOffset = 3 })
  await next.click()
  await page.waitForFunction(() => typeof window.releaseOld === 'function')
  await page.evaluate(() => { window.fixture.fileId = 'C' })
  await page.getByText('C-0', { exact: true }).waitFor()
  await page.evaluate(() => window.releaseOld())
  await page.waitForFunction(() => window.oldResolved === true)
  await page.getByText('C-0', { exact: true }).waitFor()
  await page.evaluate(() => { window.fixture.fileId = 'deep'; window.fixture.startLine = 10001 })
  await page.getByText('deep-10000', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('deep-9933', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('deep-9866', { exact: true }).waitFor()
  await next.click()
  await page.getByText('deep-9933', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('deep-9866', { exact: true }).waitFor()
  await next.click()
  await page.getByText('deep-9933', { exact: true }).waitFor()
  await next.click()
  await page.getByText('deep-10000', { exact: true }).waitFor()
  await page.evaluate(() => { window.fixture.fileId = 'single' })
  await page.getByText('single-10000', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('single-9999', { exact: true }).waitFor()
  const calls = await page.evaluate(() => window.calls)
  const offsets = calls.map(([file, offset]) => `${file}:${offset}`)
  const expected = ['A:0', 'A:3', 'A:7', 'A:3', 'A:7', 'A:7', 'A:3', 'A:0', 'B:0', 'B:3', 'C:0']
  if (JSON.stringify(offsets.slice(0, expected.length)) !== JSON.stringify(expected)) throw Error(JSON.stringify(offsets))
  const deepCalls = calls.filter(([file]) => file === 'deep')
  if (deepCalls.length > 22) throw Error(`深层分页请求过多: ${deepCalls.length}`)
  if (calls.filter(([file]) => file === 'single').length > 9) throw Error('单行窗口请求过多')
  const restored = deepCalls.filter(([, offset]) => offset === 9933)
  if (restored.some(([, , size]) => size !== 67)) throw Error(`窗口大小未恢复: ${JSON.stringify(restored)}`)
  await page.evaluate(() => { window.fixture.fileId = 'oversized'; window.fixture.startLine = 1001 })
  await page.getByText('oversized-1001', { exact: true }).waitFor()
  await previous.click()
  await page.getByText('oversized-901', { exact: true }).waitFor()
  const visibleLines = await page.locator('.reader-line-text').allTextContents()
  const expectedLines = Array.from({ length: 100 }, (_, index) => `oversized-${index + 901}`)
  if (JSON.stringify(visibleLines) !== JSON.stringify(expectedLines)) throw Error('超长行后的上一页缺失连续正文')
  await page.locator('.external-document-reader').screenshot({ path: '/tmp/yuxi-reader-isolated.png' })
  for (const message of ['网络连接失败', '无权读取该知识库']) {
    await page.evaluate(() => { window.fixture.startLine = 1002 })
    await page.getByText('oversized-1002', { exact: true }).waitFor()
    await page.evaluate(() => { window.fixture.startLine = 1001 })
    await page.getByText('oversized-1001', { exact: true }).waitFor()
    const count = await page.evaluate(() => window.calls.length)
    await page.evaluate((value) => { window.failPrevious = value }, message)
    await previous.click()
    await page.getByRole('alert').getByText(message).waitFor()
    if (await page.evaluate(() => window.calls.length) !== count + 1) throw Error('网络或权限错误被错误收窄')
    await page.locator('.external-document-reader').screenshot({ path: '/tmp/yuxi-reader-error.png' })
    await page.evaluate(() => { window.failPrevious = null })
  }
  await page.getByText('重新读取').click()
  await page.getByText('oversized-901', { exact: true }).waitFor()
  return { offsets, displayed: await page.locator('.reader-content').innerText() }
}
